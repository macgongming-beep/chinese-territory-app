-- 건물의 **세대를 다 파악했는가** 를 사람이 표시할 수 있게 한다.
--
-- 왜 (2026-08-31):
--   지도 핀이 "등록된 세대가 다 방문됐나" 만 보고 초록(완료)으로 바뀌었다.
--   그런데 104·105호만 등록된 건물이면 둘만 가도 100% 다. 실제로는 호수가
--   더 있는데 **'완료'로 보여서 아무도 안 갔다.**
--
--   시스템은 '등록된 세대' 만 안다. **그 건물에 몇 세대가 있는지는 사람만 안다.**
--   그래서 그 사실을 물어보는 칸을 만든다. 표시가 없으면 완료로 치지 않는다.
--
-- ⚠ 기본값은 false 다. 즉 **기존 건물이 전부 '확인 필요'** 가 된다.
--   화면이 갑자기 바뀌어 보이지만 그게 지금의 진실이다 — 아무도 파악했다고
--   말한 적이 없다. 봉사하면서 하나씩 채워진다.

alter table public.buildings
  add column if not exists units_surveyed boolean not null default false;

comment on column public.buildings.units_surveyed is
  '세대를 다 파악했는가. false 면 등록 세대를 다 방문해도 완료로 치지 않는다.';
